def load_existing() -> dict[str, str]:
    """Read any existing .env so re-running the script can show current values as defaults."""
    existing: dict[str, str] = {}
    if not ENV_PATH.exists():
        return existing
    for line in ENV_PATH.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        existing[key.strip()] = value.strip()
    return existing


def prompt(field_name: str, description: str, default: str | None, required: bool) -> str:
    suggestion = default if default else ""
    label = f"{description}"
    if suggestion:
        label += f" [{suggestion}]"
    label += ": "

    while True:
        value = input(label).strip()
        if not value:
            value = suggestion
        if value or not required:
            return value
        print(f"  {field_name} is required, please enter a value.")


def main() -> None:
    print("Instagram Collector Bot - configuration setup")
    print(f"Writing to: {ENV_PATH}\n")

    existing = load_existing()
    values: dict[str, str] = {}

    for field_name, description, default, required in FIELDS:
        current_default = existing.get(field_name, default)
        values[field_name] = prompt(field_name, description, current_default, required)

    lines = ["# Instagram Collector Bot configuration", "# Generated by setup_env.py", ""]
    for field_name, _, _, _ in FIELDS:
        lines.append(f"{field_name}={values[field_name]}")

    ENV_PATH.write_text("\n".join(lines) + "\n")
    # Keep the file private since it holds the bot token.
    try:
        os.chmod(ENV_PATH, 0o600)
    except OSError:
        pass

    print(f"\nSaved. {ENV_PATH} now holds your configuration.")
    print("Run the bot normally with: python insta_collector_bot.py")


if __name__ == "__main__":
    main()
